// #402: the first screen without the whole Galmuri11 (Regular 505 KB + Bold 167 KB woff2). Writes a subset of each weight with the characters the office
// shows (ASCII and Latin-1, punctuation and arrows, the 2,350 Hangul syllables of KS X 1001, the Hangul jamo, and every other character written in src/),
// and src/styles/fonts.subset.css: the subset faces with their unicode-range, the whole fonts with the rest (so a rare syllable in live data still draws,
// and `document.fonts.load()` of a family only ever fetches the subset). Run after changing UI text with characters outside the set:
//   node scripts/font-subset.mjs        (fontSubset.test.ts fails when src/ has a character the subset lacks)
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import subsetFont from 'subset-font'

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const FONTS = join(ROOT, 'node_modules/galmuri/dist')
const OUT = join(ROOT, 'src/assets/fonts')

/** the characters written in src/ (the UI's own words), as code points */
export function sourceChars(dir = join(ROOT, 'src')) {
  const out = new Set()
  const walk = (d) => {
    for (const f of readdirSync(d)) {
      const p = join(d, f)
      if (statSync(p).isDirectory()) walk(p)
      else if (/\.(tsx?|css|json)$/.test(f) && !/\.test\.tsx?$/.test(f) && !/\.fixture\.ts$/.test(f)) for (const ch of readFileSync(p, 'utf8')) out.add(ch.codePointAt(0))
    }
  }
  walk(dir)
  return out
}

/** the 2,350 Hangul syllables of KS X 1001 (EUC-KR rows 0xB0–0xC8) */
function ksx1001() {
  const dec = new TextDecoder('euc-kr')
  const out = []
  for (let r = 0xb0; r <= 0xc8; r++) for (let c = 0xa1; c <= 0xfe; c++) out.push(dec.decode(new Uint8Array([r, c])).codePointAt(0))
  return out
}

const span = (a, b) => Array.from({ length: b - a + 1 }, (_, k) => a + k)
const points = new Set([
  ...span(0x20, 0x7e),
  ...span(0xa0, 0xff),
  ...span(0x2010, 0x2027),
  ...span(0x2030, 0x205e),
  ...span(0x2190, 0x2199),
  ...span(0x3000, 0x303f),
  ...span(0x3131, 0x318e),
  ...ksx1001(),
  ...[...sourceChars()].filter((c) => c >= 0x20 && c !== 0xfeff),
])

/** code points as CSS unicode-range parts */
function ranges(cps) {
  const s = [...cps].sort((a, b) => a - b)
  const out = []
  for (let i = 0; i < s.length; ) {
    let j = i
    while (j + 1 < s.length && s[j + 1] === s[j] + 1) j++
    out.push(s[i] === s[j] ? `U+${s[i].toString(16)}` : `U+${s[i].toString(16)}-${s[j].toString(16)}`)
    i = j + 1
  }
  return out
}
/** everything else, as ranges: the whole fonts' share */
function rest(cps) {
  const s = [...cps].sort((a, b) => a - b)
  const out = []
  let from = 0
  for (const c of s) {
    if (c > from) out.push(from === c - 1 ? `U+${from.toString(16)}` : `U+${from.toString(16)}-${(c - 1).toString(16)}`)
    from = c + 1
  }
  out.push(`U+${from.toString(16)}-10ffff`)
  return out
}

mkdirSync(OUT, { recursive: true })
const text = String.fromCodePoint(...points)
for (const [src, dst] of [['Galmuri11.ttf', 'Galmuri11-subset.woff2'], ['Galmuri11-Bold.ttf', 'Galmuri11-Bold-subset.woff2']]) {
  // OFL 1.1 §2: the copyright and the licence go with the modified font: keep the name table's 0 (copyright), 13 (licence), 14 (licence URL)
  const buf = await subsetFont(readFileSync(join(FONTS, src)), text, { targetFormat: 'woff2', preserveNameIds: [0, 13, 14] })
  writeFileSync(join(OUT, dst), buf)
  console.log(dst, `${(buf.length / 1024).toFixed(1)} KB`, `(${(statSync(join(FONTS, src.replace('.ttf', '.woff2'))).size / 1024).toFixed(1)} KB whole)`)
}
const inSet = ranges(points).join(', ')
const others = rest(points).join(', ')
const face = (weight, file, range) => `@font-face {\n  font-family: 'Galmuri11';\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('${file}') format('woff2');\n  unicode-range: ${range};\n}\n`
writeFileSync(
  join(ROOT, 'src/styles/fonts.css'),
  `/* Galmuri11 © 2019–2025 Lee Minseo, SIL Open Font License 1.1, https://openfontlicense.org — subset
   (https://galmuri.quiple.dev; the subsets keep the font's own copyright and licence records, name IDs 0 · 13 · 14)
   GENERATED by scripts/font-subset.mjs (#402). Do not edit by hand: change the script and run node scripts/font-subset.mjs.
   Self-hosted from the galmuri npm package like the desk room (rowansong.dev src/styles/global.css); only the two weights the office uses (tokens.css
   --font-pixel). Each weight is two faces that never overlap: the subset (${points.size} characters: the office's own words, KS X 1001 Hangul, ASCII and
   punctuation) for the first screen, the whole font for anything else (a rare syllable in live data), fetched only when such a character shows. */
${face(400, '../assets/fonts/Galmuri11-subset.woff2', inSet)}${face(700, '../assets/fonts/Galmuri11-Bold-subset.woff2', inSet)}${face(400, '../../node_modules/galmuri/dist/Galmuri11.woff2', others)}${face(700, '../../node_modules/galmuri/dist/Galmuri11-Bold.woff2', others)}`,
)
