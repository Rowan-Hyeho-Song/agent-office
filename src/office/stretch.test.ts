// #490 B (play.md 9.3 기지개, #512 판정): at the top of the stretch both hands are out in a V and their undersides 6 cm over the top of the head and what it
// wears (hat, ring; not the thin antenna, tip or fork), and 4 cm clear of the head everywhere. The height is per agent (stretch.data.ts):
//   STRETCH_WRITE=1 npx vitest run src/office/stretch.test.ts     (measures and rewrites stretch.data.ts)
import { writeFileSync } from 'node:fs'
import { Box3, Vector3, type Mesh, type Object3D } from 'three'
import { describe, expect, it } from 'vitest'
import type { Goal } from './director'
import { GAP_MOTION } from './gapMotion'
import { loadOffice, stubCanvas } from './glbLoad'
import { GRAPH } from './navSpots.fixture'
import { AgentRig, buildRig } from './rig'
import { STRETCH_ABOVE } from './stretch.data'

stubCanvas()
const DT = 1 / 60
const OVER = 0.06
const THIN = /(_tip|_fork|antenna)$/

/** every vertex of an object's visible meshes, in world */
function points(o: Object3D, skip?: RegExp): Vector3[] {
  const out: Vector3[] = []
  o.updateMatrixWorld(true)
  o.traverseVisible((m) => {
    const g = (m as Mesh).geometry?.getAttribute('position')
    if (!(m as Mesh).isMesh || !g || (skip && skip.test(m.name))) return
    for (let i = 0; i < g.count; i++) out.push(new Vector3().fromBufferAttribute(g, i).applyMatrix4(m.matrixWorld))
  })
  return out
}

/** the stretch of one agent at the coffee machine, measured at the end of its hold at the top: the hands' lowest point over the head's top, the nearest they come to the head, how far apart */
async function top(seat: number, above: number | null) {
  const { scene, nodes } = await loadOffice()
  const id = `agent_${seat}`
  const rig = new AgentRig(id, seat, buildRig(scene, nodes, seat), '#ffffff')
  rig.stretchAt = above
  const spot = GRAPH.spots.coffee
  rig.x = spot.x
  rig.z = spot.z
  rig.heading = spot.ry
  let t = 0
  const step = (g: Goal) => {
    rig.setGoal(g, GRAPH)
    rig.update(DT, (t += DT), GRAPH, { [id]: rig }, false)
    rig.applyDrive('l', t, false)
    rig.applyDrive('r', t, false)
  }
  for (let k = 0; k < 90; k++) step({ spot: 'coffee', pose: 'idle', label: '' })
  const t0 = t
  // the end of the hold at the top (the hands have caught up with it)
  while (t - t0 < GAP_MOTION.stretchDelayS + GAP_MOTION.stretchS * (2 / 3) - DT) step({ spot: 'coffee', pose: 'idle', gap: 'stretch', label: '' })
  const head = points(rig.parts.head, THIN)
  const headTop = Math.max(...head.map((p) => p.y))
  const hands = (['l', 'r'] as const).map((s) => points(rig.parts.hands[s].node))
  const low = Math.min(...hands.flat().map((p) => p.y))
  let near = Infinity
  for (const h of hands) for (const p of h) for (const q of head) near = Math.min(near, p.distanceToSquared(q))
  const mid = hands.map((h) => new Box3().setFromPoints(h).getCenter(new Vector3()))
  return { over: low - headTop, near: Math.sqrt(near), apart: mid[0].distanceTo(mid[1]) }
}

describe('the stretch over the head (#490 B, #512)', () => {
  if (process.env.STRETCH_WRITE) {
    it('measures each agent and writes stretch.data.ts', async () => {
      const out: Record<number, number> = {}
      for (const seat of [0, 1, 2, 3, 4]) {
        // the hands' height follows the setting one for one: two rounds from a first guess
        let above = 0.38
        for (let k = 0; k < 2; k++) above += OVER - (await top(seat, above)).over
        out[seat] = Math.round(above * 10000) / 10000
      }
      writeFileSync(
        new URL('./stretch.data.ts', import.meta.url),
        `// GENERATED by src/office/stretch.test.ts (STRETCH_WRITE=1 npx vitest run src/office/stretch.test.ts). Do not edit by hand.
// #490 B (play.md 9.3 기지개, #512 판정): per agent, how far above the head's rest the hands go at the top of the stretch (m), so that their undersides are
// 6 cm over the top of the head and what it wears (hat, ring; not the thin antenna, tip or fork).

export const STRETCH_ABOVE: Record<number, number> = {
${Object.entries(out).map(([k, v]) => `  ${k}: ${v},`).join('\n')}
}
`,
      )
    }, 600_000)
    return
  }
  for (const seat of [0, 1, 2, 3, 4]) {
    it(`agent_${seat}: the hands' undersides 6 cm over the head and what it wears, 4 cm clear of it, out in a V`, async () => {
      expect(STRETCH_ABOVE[seat], 'measured (STRETCH_WRITE=1)').toBeTypeOf('number')
      const r = await top(seat, null)
      expect(r.over).toBeGreaterThanOrEqual(OVER - 0.005)
      expect(r.over).toBeLessThanOrEqual(OVER + 0.005)
      expect(r.near, 'clear of the head').toBeGreaterThanOrEqual(0.04)
      expect(r.apart, 'a V').toBeGreaterThan(0.4)
    }, 120_000)
  }
})
