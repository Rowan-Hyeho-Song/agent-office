  review: ['....####....', '....####....', '.....##.....', '.....##.....', '..########..', '.##########.', '.##########.', '............', '.##########.', '.#........#.', '.##########.', '............'],
  key: ['............', '............', '..###.......', '.#...#......', '.#...#######', '.#...#..#.##', '..###...#..#', '............', '............', '............', '............', '............'],
