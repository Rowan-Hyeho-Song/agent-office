// #519 (lounge-props.md 1 · 1a): lying on the east seat, the head is on the pillow (the back of it 5 mm over the pillow's top, ±5 mm), the crown not past
// the armrest's outside face; the hands lie palm down on the cushion at the belly (their undersides 0–1 cm over it), in a line with the head. The heights
// are per agent (lie.data.ts):
//   LIE_WRITE=1 npx vitest run src/office/lie.test.ts     (measures and rewrites lie.data.ts)
import { writeFileSync } from 'node:fs'
import { Raycaster, Vector3, type Mesh, type Object3D } from 'three'
import { describe, expect, it } from 'vitest'
import type { Goal } from './director'
import { loadOffice, stubCanvas } from './glbLoad'
import { GRAPH } from './navSpots.fixture'
import { AgentRig, buildRig } from './rig'
import { LIE_POSE } from './lie.data'

stubCanvas()
const DT = 1 / 60
const OVER = 0.005
/** the east seat's cushion top and the armrest's outside face (lounge-props.md, #519) */
const CUSHION_Y = 0.44
const ARMREST_OUT_Z = 2.245
const THIN = /(_tip|_fork|antenna|_glow)$/

function points(o: Object3D, skip?: RegExp): Vector3[] {
  const out: Vector3[] = []
  o.updateMatrixWorld(true)
  o.traverseVisible((m) => {
    const g = (m as Mesh).geometry?.getAttribute('position')
    if (!(m as Mesh).isMesh || !g || (skip && skip.test(m.name))) return
    for (let i = 0; i < g.count; i++) out.push(new Vector3().fromBufferAttribute(g, i).applyMatrix4(m.matrixWorld))
  })
  return out
}

/** one agent lying on the east seat, settled: the head's lowest point over the pillow's top there, its crown's z, the hands' lowest over the cushion, where they are */
async function lie(seat: number, at: { headY: number; handY: number } | null) {
  const { scene, nodes } = await loadOffice()
  const id = `agent_${seat}`
  const rig = new AgentRig(id, seat, buildRig(scene, nodes, seat), '#ffffff')
  rig.lieAt = at
  // the lying seat's head point, from the model (as Agents.tsx does: nav extras lie + head)
  const ud = scene.getObjectByName('nav_sofa_3')!.userData as { lie?: boolean; head?: number[] }
  GRAPH.spots.sofa_3.head = { x: ud.head![0], z: ud.head![1] }
  let t = 0
  const goal = { spot: 'sofa_3', pose: 'sofa', label: '' } as Goal
  for (let k = 0; k < 8 / DT; k++) {
    rig.setGoal(goal, GRAPH)
    rig.update(DT, (t += DT), GRAPH, { [id]: rig }, false)
    rig.applyDrive('l', t, false)
    rig.applyDrive('r', t, false)
  }
  const head = points(rig.parts.head, THIN)
  const lowest = head.reduce((a, b) => (b.y < a.y ? b : a))
  const pillow = scene.getObjectByName('prop_pillow_1')!
  const hit = new Raycaster(new Vector3(lowest.x, 1.5, lowest.z), new Vector3(0, -1, 0), 0, 1.5).intersectObject(pillow, true)[0]
  const hands = (['l', 'r'] as const).map((s) => points(rig.parts.hands[s].node))
  const handLow = Math.min(...hands.flat().map((p) => p.y))
  const mid = hands.map((h) => h.reduce((a, b) => a.add(b), new Vector3()).multiplyScalar(1 / h.length))
  return {
    over: lowest.y - (hit?.point.y ?? NaN),
    onPillow: !!hit,
    crown: Math.min(...head.map((p) => p.z)),
    hands: handLow - CUSHION_Y,
    handMid: mid[0].clone().add(mid[1]).multiplyScalar(0.5),
    head: rig.parts.head.getWorldPosition(new Vector3()),
  }
}

describe('lying on the east seat (#519)', () => {
  if (process.env.LIE_WRITE) {
    it('measures each agent and writes lie.data.ts', async () => {
      const out: Record<number, { headY: number; handY: number }> = {}
      for (const seat of [0, 1, 2, 3, 4]) {
        let at = { headY: 0.75, handY: 0.48 }
        for (let k = 0; k < 2; k++) {
          const r = await lie(seat, at)
          at = { headY: at.headY + OVER - r.over, handY: at.handY + OVER - r.hands }
        }
        out[seat] = { headY: Math.round(at.headY * 10000) / 10000, handY: Math.round(at.handY * 10000) / 10000 }
      }
      writeFileSync(
        new URL('./lie.data.ts', import.meta.url),
        `// GENERATED by src/office/lie.test.ts (LIE_WRITE=1 npx vitest run src/office/lie.test.ts). Do not edit by hand.
// #519 (lounge-props.md 1): per agent, lying on the east seat: the head's height (its back 5 mm over the pillow) and the hands' (their undersides 5 mm over
// the cushion), m.

export const LIE_POSE: Record<number, { headY: number; handY: number }> = {
${Object.entries(out).map(([k, v]) => `  ${k}: { headY: ${v.headY}, handY: ${v.handY} },`).join('\n')}
}
`,
      )
    }, 600_000)
    return
  }
  for (const seat of [0, 1, 2, 3, 4]) {
    it(`agent_${seat}: the head on the pillow (5 mm ± 5 mm), the crown inside the armrest; the hands on the cushion at the belly, in line with the head`, async () => {
      expect(LIE_POSE[seat], 'measured (LIE_WRITE=1)').toBeDefined()
      const r = await lie(seat, null)
      expect(r.onPillow, 'over the pillow').toBe(true)
      expect(r.over).toBeGreaterThanOrEqual(0)
      expect(r.over).toBeLessThanOrEqual(0.01)
      expect(r.crown, 'not past the armrest').toBeGreaterThanOrEqual(ARMREST_OUT_Z)
      expect(r.head.z, 'the head on the pillow, south of the armrest').toBeCloseTo(2.7, 2)
      expect(r.hands, 'the hands on the cushion').toBeGreaterThanOrEqual(0)
      expect(r.hands).toBeLessThanOrEqual(0.01)
      expect(r.handMid.z - r.head.z, 'at the belly').toBeGreaterThan(0.3)
      expect(Math.abs(r.handMid.x - 4.1), 'in line with the head').toBeLessThan(0.06)
    }, 120_000)
  }
})
